import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { PARTY_GEOMETRY } from '../src/party-geometry.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const work = join(root, 'work/party-v2');
await mkdir(work, { recursive: true });
const directions = JSON.parse(await readFile(join(root, 'docs/party-art-direction-v2.json'), 'utf8'));
const artwork = Object.fromEntries(directions.map(({ id, name, style, framing, category, cropAnchor, cropZoom }) =>
  [id, { name, style, framing, category, ...(cropAnchor && { cropAnchor }), ...(cropZoom && { cropZoom }) }]));
const geometry = {
  ...PARTY_GEOMETRY,
  pieces: PARTY_GEOMETRY.pieces.map(piece => ({ ...piece, ...artwork[piece.id] })),
};
await writeFile(join(work, 'geometry.json'), JSON.stringify(geometry));
const partial = process.argv.includes('--partial');
const result = spawnSync(process.env.PAWZZLE_PYTHON || 'python3',
  [join(root, 'scripts/prepare-party-art.py'), ...(partial ? ['--partial'] : [])], { stdio: 'inherit', cwd: root });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
if (!partial) {
  // Publish the revised mapping only after all thirty source images assemble.
  await writeFile(join(root, 'src/party-data.js'), `// Generated by npm run generate:party from independently generated full-bleed sources.\nimport { PARTY_GEOMETRY } from './party-geometry.js';\nconst artwork = ${JSON.stringify(artwork, null, 2)};\nexport const PARTY_DATA = {\n  id: 'dog-party-v1', artRevision: 'full-bleed-v2', name: '汪汪游乐园',\n  width: 600, height: 600, pixelScale: 3,\n  outline: PARTY_GEOMETRY.outline,\n  image: '/assets/party-dogs-v2.png', blueprint: '/assets/party-blueprint.svg',\n  pipeline: 'individual full-bleed dog images → cover crop → exact contour mask',\n  pieces: PARTY_GEOMETRY.pieces.map(({ points, edges, artBounds, ...piece }) => ({\n    ...piece, ...artwork[piece.id], fill: '#9b7552',\n    source: '/assets/party-source-v2/' + piece.id + '.png',\n    image: '/assets/party-dogs-v2/' + piece.id + '.png',\n  })),\n};\nexport default PARTY_DATA;\n`);
}
